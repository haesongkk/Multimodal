import unreal as u,runpy
from editor_toolset.toolsets.blueprint import BlueprintTools as B,_BlueprintCache
assets=u.get_editor_subsystem(u.EditorAssetSubsystem)
path='/Game/Multimodal/03_Graphics/Materials/Buildings/ClientHome/M_CH_ClearSky'
m=u.load_asset(path) or u.AssetToolsHelpers.get_asset_tools().create_asset('M_CH_ClearSky','/Game/Multimodal/03_Graphics/Materials/Buildings/ClientHome',u.Material,u.MaterialFactoryNew())
M=u.MaterialEditingLibrary
M.delete_all_material_expressions(m)
m.set_editor_property('shading_model',u.MaterialShadingModel.MSM_UNLIT)
m.set_editor_property('two_sided',True)
m.set_editor_property('is_sky',False)
c=M.create_material_expression(m,u.MaterialExpressionVectorParameter,-250,0)
c.set_editor_property('parameter_name','SkyColor');c.set_editor_property('default_value',u.LinearColor(.85,2.0,3.0,1.0))
assert M.connect_material_property(c,'',u.MaterialProperty.MP_EMISSIVE_COLOR)
assert not M.recompile_material(m)
assert assets.save_loaded_asset(m,False)
a=next(a for a in u.get_editor_subsystem(u.EditorActorSubsystem).get_all_level_actors() if a.get_actor_label()=='SkySphere')
a.get_component_by_class(u.StaticMeshComponent).set_material(0,u.load_asset('/Game/ExternalAssets/StylizedKitchen/Materials/MI_Master_Sky'))
actors=u.get_editor_subsystem(u.EditorActorSubsystem)
back=next((a for a in actors.get_all_level_actors() if a.get_actor_label()=='CH_ClearSky_Backdrop'),None)
if not back:back=actors.spawn_actor_from_class(u.StaticMeshActor,u.Vector(0,0,-50))
back.set_actor_label('CH_ClearSky_Backdrop');back.set_actor_scale3d(u.Vector(1000,1000,1));back.set_actor_enable_collision(False)
bc=back.get_component_by_class(u.StaticMeshComponent);bc.set_static_mesh(u.load_asset('/Engine/BasicShapes/Plane'));bc.set_material(0,m)
bc.set_editor_property('cast_shadow',False);bc.set_editor_property('affect_distance_field_lighting',False)
back.set_folder_path('ClientHome/Background')
assert u.get_editor_subsystem(u.LevelEditorSubsystem).save_current_level()
hud=u.load_asset('/Game/Multimodal/02_Blueprints/Framework/ClientHome/BP_CH_HUD_Minimal')
lang=u.InternationalizationLibrary.get_current_language();u.InternationalizationLibrary.set_current_language('en',False)
try:
 _BlueprintCache.invalidate(hud)
 runpy.run_path('D:/Multimodal/Build/Tools/ClientHome/completed_journal_hint.py')['configure'](hud,B)
 B.compile_blueprint(hud,True)
 assert assets.save_loaded_asset(hud,False)
 u.log('CLEAR_SKY_AND_COMPLETED_HINT_SAVED')
finally:u.InternationalizationLibrary.set_current_language(lang,False)
